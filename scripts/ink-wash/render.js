// regenerates public/images/ink-wash.webp from paint.js (uses the preinstalled playwright chromium)
const fs = require('fs'), path = require('path')
const { chromium } = require('playwright')
;(async () => {
  const src = fs.readFileSync(path.join(__dirname, 'paint.js'), 'utf8')
  const out = process.argv[2] || path.join(__dirname, '../../public/images/ink-wash.webp')
  const browser = await chromium.launch(); const page = await browser.newPage()
  await page.setContent('<canvas id="c" width="2400" height="1400"></canvas>')
  const url = await page.evaluate(code => {
    eval(code + ';window.paintInkWash = paintInkWash')
    const c = document.getElementById('c'); window.paintInkWash(c, 1751)
    return c.toDataURL('image/webp', 0.86)
  }, src)
  fs.writeFileSync(out, Buffer.from(url.split(',')[1], 'base64'))
  console.log('wrote', out, Math.round(fs.statSync(out).size / 1024) + 'KB')
  await browser.close()
})()
